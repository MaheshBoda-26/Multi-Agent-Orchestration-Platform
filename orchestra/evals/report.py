"""Generate evals/results.md from the stored per-repeat outputs (Task 36).

One command, one table: pass rate and mean score per config, mean +/- spread
across repeats. README numbers may come only from this file (never-cut claim).
"""
import json
import statistics
from pathlib import Path
from typing import Any, Dict, List

RESULTS_DIR = Path(__file__).resolve().parent / "output"
REPORT_PATH = Path(__file__).resolve().parent / "results.md"


def _load_summaries() -> Dict[str, List[Dict[str, Any]]]:
    by_config: Dict[str, List[Dict[str, Any]]] = {}
    for path in sorted(RESULTS_DIR.glob("*-r*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        summary = data.get("summary") or {}
        name = summary.get("config") or path.stem.rsplit("-r", 1)[0]
        by_config.setdefault(name, []).append(summary)
    return by_config


def generate_report(results_dir: Path = RESULTS_DIR, output: Path = REPORT_PATH) -> str:
    by_config = _load_summaries()
    if not by_config:
        lines = [
            "# Eval results",
            "",
            "No eval outputs found. Run `uv run python -m evals.run` first.",
            "",
        ]
        output.write_text("\n".join(lines))
        return "\n".join(lines)

    lines = [
        "# Eval results",
        "",
        "Generated by `uv run python -m evals.report`. Every number the README",
        "quotes must come from this table.",
        "",
        "| Config | Repeats | Pass rate (mean) | Pass rate (spread) | Mean score |",
        "|---|---|---|---|---|",
    ]
    for name, summaries in by_config.items():
        n = len(summaries)
        rates = [s["passed"] / s["tasks"] if s["tasks"] else 0.0 for s in summaries]
        scores = [s.get("mean_score", 0.0) for s in summaries]
        mean_rate = statistics.mean(rates) if rates else 0.0
        spread = (
            f"{min(rates):.1%}-{max(rates):.1%}"
            if n > 1 and max(rates) != min(rates)
            else f"{mean_rate:.1%}"
        )
        lines.append(
            f"| {name} | {n} | {mean_rate:.1%} | {spread} | "
            f"{statistics.mean(scores) if scores else 0:.3f} |"
        )

    baseline = by_config.get("baseline")
    if baseline:
        base_rate = statistics.mean(
            s["passed"] / s["tasks"] if s["tasks"] else 0.0 for s in baseline
        )
        lines += [
            "",
            f"Single-agent baseline pass rate: {base_rate:.1%}. "
            "Deltas above this line are the multi-agent system's contribution.",
        ]

    text = "\n".join(lines) + "\n"
    output.write_text(text)
    return text


if __name__ == "__main__":
    print(generate_report())
